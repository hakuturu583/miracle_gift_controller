"""Generate crates/miragift-core/src/table.rs from ohtake/miracle-light-controller src/mlc.ts (ISC)."""
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
def pat(s):
    items = [x.strip().strip("'") for x in s.split(",") if x.strip()]
    return (int(items[0]), items[1:]) if items else (0, [])
named = []
for m in re.finditer(r"t = document.getElementById\('(\w+)'\)|insertControl\(t, '(\d{7})', '([^']+)', \[([^\]]*)\]\);", src):
    if m.group(1): group = m.group(1); continue
    if m.group(2): named.append((group, m.group(2), m.group(3), *pat(m.group(4))))
allc = []
for m in re.finditer(r"\{ command: '(\d{7})', pattern: \[([^\]]*)\](, devices: \['strawberry'\])? \}", src):
    allc.append((m.group(1), *pat(m.group(2)), bool(m.group(3))))
assert len(allc) == 128, len(allc)
def rs_colors(cs): return "&[" + ", ".join("Color::" + c.capitalize() for c in cs) + "]"
out = ["// @generated by tools/gen_table.py from ohtake/miracle-light-controller (ISC License).", "use crate::{Color, NamedCommand, KnownCommand};", ""]
out.append("pub static NAMED: &[NamedCommand] = &[")
for g, c, n, bpm, cs in named:
    out.append(f'    NamedCommand {{ group: "{g}", name: "{n}", code: "{c}", bpm: {bpm}, colors: {rs_colors(cs)} }},')
out.append("];\n")
out.append("pub static ALL: &[KnownCommand] = &[")
for c, bpm, cs, st in allc:
    out.append(f'    KnownCommand {{ code: "{c}", bpm: {bpm}, colors: {rs_colors(cs)}, strawberry_only: {"true" if st else "false"} }},')
out.append("];")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(named), "named,", len(allc), "all")
